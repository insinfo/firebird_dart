// Generates lib/src/error_codes.dart (status code -> symbolic name) from a
// Firebird iberror.h header.
//
//   dart run tool/gen_error_codes.dart "C:\Program Files\Firebird\Firebird_2_5\include\iberror.h"
import 'dart:io';

void main(List<String> args) {
  if (args.isEmpty) {
    stderr.writeln('usage: dart run tool/gen_error_codes.dart <iberror.h>');
    exit(64);
  }
  final text = File(args.first).readAsStringSync();
  final re = RegExp(r'const ISC_STATUS (isc_\w+)\s*=\s*(\d+)L;');
  final codes = <int, String>{};
  for (final m in re.allMatches(text)) {
    final value = int.parse(m.group(2)!);
    if (value <= 335544320) continue; // facility/base/arg constants
    codes.putIfAbsent(value, () => m.group(1)!);
  }
  final keys = codes.keys.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_error_codes.dart. Do not edit.')
    ..writeln('// Symbolic names of Firebird status codes.')
    ..writeln()
    ..writeln('const Map<int, String> fbErrorCodeNames = {');
  for (final k in keys) {
    out.writeln("  $k: '${codes[k]}',");
  }
  out.writeln('};');
  File('lib/src/error_codes.dart').writeAsStringSync(out.toString());
  stdout.writeln('${keys.length} codes written to lib/src/error_codes.dart');
}
